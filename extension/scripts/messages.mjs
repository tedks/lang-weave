// Writes src/messages-en.js from _locales/en/messages.json, the English source of truth.
// `node scripts/messages.mjs` rewrites it; `--check` exits non-zero when it is stale.
// Named placeholders are resolved the way Chrome resolves them, so EN holds $1..$9 only.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
export const MESSAGES = join(ROOT, '_locales', 'en', 'messages.json');
export const MIRROR = join(ROOT, 'src', 'messages-en.js');

export function resolveMessage(name, entry) {
  const placeholders = Object.fromEntries(Object.entries(entry.placeholders ?? {})
    .map(([key, value]) => [key.toLowerCase(), value.content]));
  return entry.message.replace(/\$([A-Za-z0-9_@]+)\$/g, (whole, key) => {
    const content = placeholders[key.toLowerCase()];
    if (content === undefined) throw new Error(`${name}: unknown placeholder ${whole}`);
    return content;
  });
}

export function mirrorSource(messages) {
  const lines = Object.entries(messages).map(([name, entry]) =>
    `  ${name}: ${JSON.stringify(resolveMessage(name, entry))},`);
  return `// Generated by scripts/messages.mjs from _locales/en/messages.json. Do not edit.\n` +
    `// The English fallback for contexts without chrome.i18n; see i18n.js.\n` +
    `export const EN = Object.freeze({\n${lines.join('\n')}\n});\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const source = mirrorSource(JSON.parse(readFileSync(MESSAGES, 'utf8')));
  if (process.argv.includes('--check')) {
    if (readFileSync(MIRROR, 'utf8') !== source) {
      console.error('src/messages-en.js is stale; run node scripts/messages.mjs');
      process.exit(1);
    }
  } else writeFileSync(MIRROR, source);
}
